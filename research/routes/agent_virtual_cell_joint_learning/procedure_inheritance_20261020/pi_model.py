"""Shared response-model family and conventional planners for the procedure-inheritance study.

One response family is used by every arm. A background's residual e = A - A_ref over P drug-pair units is generated by one of m learned regimes
(a profile vector), by the null regime (zero profile) or by an unexplained broad component U:
    regime c:   r_p = y_p - A_ref_p ~ N(L_c[p], s2)        (s2 = unexplained cell heterogeneity + measurement noise)
    unexplained U: r_p ~ N(0, tau2)
Observed pairs keep a Bayesian shrunk value (never a free-floating prediction); shortlist = top-K posterior-mean scores.

Conventional planners over this family (all exact up to Gauss-Hermite quadrature):
    Kg1  one-step knowledge gradient: E[max-shortlist utility after one read] - current. Outcomes and updates use the SAME mixture, and recorded values stay fixed.
    Kg2  two-step lookahead: first read chosen to maximise E[ current-after + max(0, best one-step gain afterwards) ].
    Exploit  measure the highest-score unmeasured pair.
Unknown exit (shared by every library arm): when the posterior mass of U exceeds 0.5 the library no longer explains the background and all later reads are direct (exploit).
"""
from __future__ import annotations

import hashlib
import os

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

import time  # noqa: E402

import numpy as np  # noqa: E402

K_SHORT = 5
EPS_STOP = 0.0003
PU = 0.05
TAU = 0.30
M2 = 0.02 ** 2
UNKNOWN_W = 0.5
GH = {g: np.polynomial.hermite.hermgauss(g) for g in (3, 5, 25)}   # production uses 3/5 nodes; 25 nodes are used by the analytical fixture


class Lib:
    """A fitted response-factor library: m regime profiles plus null and U. The same object is serialised and used at every invocation."""

    def __init__(self, L, counts, s2, pu=PU, tau=TAU, m2=M2):
        self.L = np.atleast_2d(np.asarray(L, float))                  # (m+1, P) row 0 = null (zeros)
        self.counts = np.asarray(counts, float)
        self.s2 = float(max(s2, 1.5 * m2))
        self.pu, self.tau2, self.m2 = float(pu), float(tau) ** 2, float(m2)
        m1, P = self.L.shape
        self.m1, self.P, self.C = m1, P, m1 + 1
        pri = (self.counts + 0.5) / (self.counts.sum() + 0.5 * m1) * (1 - self.pu)
        self.logprior = np.log(np.append(pri, self.pu))
        self.Lfull = np.vstack([self.L, np.zeros((1, P))])
        self.sd = np.sqrt(np.append(np.full(m1, self.s2), self.tau2))
        self.k = np.append(np.full(m1, max(self.s2 - self.m2, 1e-6) / self.s2), (self.tau2 - self.m2) / self.tau2)

    @property
    def n_regimes(self):
        return self.m1 - 1

    def fingerprint(self):
        h = hashlib.sha256()
        h.update(np.round(self.L, 5).tobytes())
        h.update(np.round(self.counts, 3).tobytes())
        h.update(repr((round(self.s2, 7), self.pu, self.tau2, self.m2)).encode())
        return h.hexdigest()

    def arrays(self):
        return {"L": self.L, "counts": self.counts, "meta": np.array([self.s2, self.pu, self.tau2 ** 0.5, self.m2])}

    @staticmethod
    def from_arrays(z, prefix=""):
        meta = z[prefix + "meta"]
        return Lib(z[prefix + "L"], z[prefix + "counts"], meta[0], meta[1], meta[2], meta[3])


def posterior(lib, obs):
    lw = lib.logprior.copy()
    for p, r in obs.items():
        lw += -0.5 * ((r - lib.Lfull[:, p]) / lib.sd) ** 2 - np.log(lib.sd)
    w = np.exp(lw - lw.max())
    return w / w.sum()


def _M(lib, obs):
    M = lib.Lfull.copy()
    for p, r in obs.items():
        M[:, p] = (1 - lib.k) * lib.Lfull[:, p] + lib.k * r
    return M


def scores(lib, a, obs, w):
    if lib is None:
        s = a.copy()
        for p, r in obs.items():
            s[p] = a[p] + r
        return s
    return a + w @ _M(lib, obs)


def topk(score, K=K_SHORT):
    idx = np.arange(len(score))
    return [int(i) for i in np.lexsort((idx, -score))[:K]]


def _topk_mean(score, K=K_SHORT):
    return float(np.sort(score)[-K:].sum() / K)


def kg1_all(lib, a, obs, w, cand, G=5):
    """One-step knowledge gradient for every candidate read (candidates must be unmeasured). Returns (gain per candidate, current expected shortlist utility)."""
    P, K = len(a), K_SHORT
    cand = np.asarray(cand, int)
    x, g = GH[G]
    g = g / np.sqrt(np.pi)
    M = _M(lib, obs)
    cur = _topk_mean(a + w @ M)
    mu = lib.Lfull[:, cand]                                                    # (C, n)
    R = mu[:, None, :] + np.sqrt(2) * lib.sd[:, None, None] * x[None, :, None]   # (C, G, n)
    om = (w[:, None] * g[None, :]).reshape(-1)
    N = lib.C * G
    R = R.reshape(N, len(cand))
    z = (R[None, :, :] - mu[:, None, :]) / lib.sd[:, None, None]
    lw = np.log(w + 1e-300)[:, None, None] - 0.5 * z ** 2 - np.log(lib.sd)[:, None, None]
    lw -= lw.max(0, keepdims=True)
    Wn = np.exp(lw)
    Wn /= Wn.sum(0, keepdims=True)                                             # (C, N, n)
    S = a[None, None, :] + np.einsum("cnj,cq->njq", Wn, M)
    own = (1 - lib.k)[:, None, None] * mu[:, None, :] + lib.k[:, None, None] * R[None, :, :]
    S[:, np.arange(len(cand)), cand] = a[cand][None, :] + (Wn * own).sum(0)
    T = np.partition(S, P - K, axis=2)[:, :, P - K:].sum(2) / K
    return (om[:, None] * T).sum(0) - cur, cur


def _state_after(lib, obs, p, r):
    o = dict(obs)
    o[p] = r
    return o


def kg2_rank(lib, a, obs, w, legal, n_dis=6, n_kg=4, G1=3, G2=3, prune=1e-3):
    """Two-step lookahead values for a screened set of first reads. Returns ([(pair, value)] best first, best one-step value)."""
    P = len(a)
    legal = np.asarray(legal, int)
    kg, cur = kg1_all(lib, a, obs, w, legal)
    mean = w @ lib.Lfull
    dis = (w[:, None] * (lib.Lfull - mean) ** 2).sum(0)[legal]
    scr = list(legal[np.lexsort((legal, -dis))[:n_dis]]) + list(legal[np.lexsort((legal, -kg))[:n_kg]])
    scr = sorted(set(int(i) for i in scr))
    x, g = GH[G1]
    g = g / np.sqrt(np.pi)
    out = []
    for p in scr:
        r_nodes = (lib.Lfull[:, p][:, None] + np.sqrt(2) * lib.sd[:, None] * x[None, :]).reshape(-1)
        om = (w[:, None] * g[None, :]).reshape(-1)
        v = 0.0
        tot = 0.0
        rest = legal[legal != p]
        for r, o in zip(r_nodes, om):
            if o < prune:
                continue
            ob = _state_after(lib, obs, p, r)
            wn = posterior(lib, ob)
            s_node = _topk_mean(scores(lib, a, ob, wn))
            if len(rest):
                kq, _ = kg1_all(lib, a, ob, wn, rest, G=G2)
                add = max(0.0, float(kq.max()))
            else:
                add = 0.0
            v += o * (s_node + add)
            tot += o
        out.append((p, float(v / tot - cur)))
    out.sort(key=lambda t: (-t[1], t[0]))
    return out, float(kg.max())


def kg2_first(lib, a, obs, w, legal, **kw):
    """Two-step lookahead choice. Returns (chosen pair or None below the stop threshold, value, best one-step value)."""
    rk, k1 = kg2_rank(lib, a, obs, w, legal, **kw)
    best, bestv = rk[0]
    return (best if bestv > EPS_STOP else None), float(bestv), k1


class Camp:
    """One background campaign: public reference a, a table of recorded reads (NaN = not available), hidden truth T only for scoring."""

    def __init__(self, a, y_table, T=None):
        self.a, self.y, self.T = np.asarray(a, float), np.asarray(y_table, float), T
        self.reads = []

    def read(self, p):
        v = self.y[p]
        if np.isnan(v):
            raise KeyError(f"pair {p} not in the recorded query log")
        self.reads.append((int(p), float(v)))
        return float(v)

    def oracle(self):
        return float(np.sort(self.T)[-K_SHORT:].mean())

    def utility(self, nom):
        return float(np.mean(self.T[list(nom)]))


class Ctx:
    def __init__(self, lib, a, obs, seq, w, step, B, log):
        self.lib, self.a, self.obs, self.seq, self.w, self.step, self.B, self.log = lib, a, obs, seq, w, step, B, log

    def legal(self):
        m = np.ones(len(self.a), bool)
        for p in self.obs:
            m[p] = False
        return np.nonzero(m)[0]


class Exploit:
    name = "exploit"

    def choose(self, c):
        s = scores(c.lib, c.a, c.obs, c.w)
        idx = c.legal()
        return int(idx[np.lexsort((idx, -s[idx]))][0]) if len(idx) else None


class Kg1:
    name = "kg1"

    def choose(self, c):
        idx = c.legal()
        if not len(idx):
            return None
        kg, _ = kg1_all(c.lib, c.a, c.obs, c.w, idx)
        if kg.max() <= EPS_STOP:
            c.log["direct_fallback"] = c.log.get("direct_fallback", 0) + 1
            return Exploit().choose(c)
        return int(idx[np.lexsort((idx, -kg))][0])


class Kg2:
    """Two-step lookahead for the first `depth_steps` reads, one-step afterwards."""
    name = "kg2"

    def __init__(self, depth_steps=2):
        self.depth_steps = depth_steps

    def choose(self, c):
        idx = c.legal()
        if not len(idx):
            return None
        if c.step <= self.depth_steps and c.B - c.step + 1 >= 2:
            p, v, k1 = kg2_first(c.lib, c.a, c.obs, c.w, idx)
            if p is None:
                c.log["direct_fallback"] = c.log.get("direct_fallback", 0) + 1
                return Exploit().choose(c)
            return p
        return Kg1().choose(c)


def run_campaign(lib, camp, B, agent, arm="", tag=None):
    """Execute one campaign. `agent.choose(ctx)` returns a pair (or None to hand over to the default one-step rule). Returns a fully logged row."""
    t0 = time.process_time()
    a = camp.a
    obs, seq, log = {}, [], {}
    exit_unknown, unknown_step = False, None
    cur = agent
    for step in range(1, B + 1):
        w = posterior(lib, obs) if lib is not None else None
        if lib is not None and not exit_unknown and obs and w[-1] > UNKNOWN_W:
            exit_unknown, unknown_step, cur = True, step, Exploit()
        ctx = Ctx(lib, a, obs, seq, w, step, B, log)
        p = cur.choose(ctx)
        if p is None:
            p = (Exploit() if exit_unknown or lib is None else Kg1()).choose(ctx)
        if p is None:
            break
        y = camp.read(p)
        obs[p] = y - a[p]
        seq.append([int(p), float(y)])
    w = posterior(lib, obs) if lib is not None else None
    nom = topk(scores(lib, a, obs, w))
    row = {"arm": arm, "queries": seq, "nominated": nom, "n_spent": len(seq), "exit_unknown": exit_unknown, "unknown_step": unknown_step,
           "post_unknown": None if w is None else round(float(w[-1]), 6), "lib_fp": None if lib is None else lib.fingerprint(), "cpu_s": time.process_time() - t0}
    row.update(log)
    if tag:
        row.update(tag)
    if camp.T is not None:
        row["utility"], row["oracle"] = camp.utility(nom), camp.oracle()
    return row
