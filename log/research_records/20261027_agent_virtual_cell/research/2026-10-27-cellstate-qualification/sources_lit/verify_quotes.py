def norm(t):
    # strip inline-LaTeX delimiters that the HTML->text extraction kept around numbers
    t = t.replace("\\(", "").replace("\\)", "")
    t = re.sub(r"\\mathrm\{([^{}]*)\}", r"\1", t)
    return re.sub(r"\s+", " ", t)


